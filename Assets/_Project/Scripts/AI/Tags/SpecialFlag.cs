namespace ReTrap
{
    // ═══════════════════════════════════════════════════════════════════════════
    //  SpecialFlag — 함정 면역/이동 태그의 특수 거동 플래그
    // ═══════════════════════════════════════════════════════════════════════════

    /// <summary>
    /// DamageType 마스크만으로 표현할 수 없는 태그별 특수 거동을 나타내는 플래그.
    /// 여러 태그가 부여되면 OR 로 조합된다.
    /// </summary>
    [System.Flags]
    public enum SpecialFlag
    {
        None              = 0,
        Hover             = 1 << 0, // 공중부양 — 가시 센서 미작동, 지면에서 살짝 떠서 이동
        AbsorbProjectile  = 1 << 1, // 스펀지 몸 — 투사체를 데미지 없이 흡수(소멸)
        FrontShieldOnly   = 1 << 2, // 철벽 방패 — 전방 화살 면역, 후방 피격은 유효
        DestroyTrapOnHit  = 1 << 3, // 함정 혐오 — 피격 시 해당 함정 영구 파괴
        CurseTrapOnHit    = 1 << 4, // 저주부르미 — 피격 시 해당 함정 저주(변이 연동, 효과 기획 미정)
        NoLandingStun     = 1 << 5, // 유연함 — 낙하 착지 경직 면역
        RetreatFromPlayer = 1 << 6, // 뒷걸음질 — 플레이어 감지 시 2칸 후퇴
        LightningRod      = 1 << 7, // 피뢰침 — 광역 피해를 자신에게 흡수 (전기/마법 함정용 예약)
        Glide             = 1 << 8, // 낙하산 — 낙하 시 활공(저속 하강)
    }
}
