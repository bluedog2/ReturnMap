namespace ReTrap
{
    // ═══════════════════════════════════════════════════════════════════════════
    //  DamageType — 함정 피해 타입 플래그
    // ═══════════════════════════════════════════════════════════════════════════

    /// <summary>
    /// 함정이 가하는 피해의 종류를 나타내는 플래그.
    /// <para>
    /// 이 열거형 하나를 <b>두 가지 용도로 겸용</b>한다: 함정 쪽에서는 단일 값(예:
    /// <see cref="Spike"/>)으로 자신의 피해 타입을 나타내고, AI 태그 쪽에서는 여러 값을
    /// OR 로 조합한 마스크(예: Spike | Arrow)로 "면역 대상 조합"을 나타낸다.
    /// </para>
    /// </summary>
    [System.Flags]
    public enum DamageType
    {
        None     = 0,
        Spike    = 1 << 0,  // 가시
        Arrow    = 1 << 1,  // 화살
        Hammer   = 1 << 2,  // 드롭 해머
        Electric = 1 << 3,  // 전기 (미래 함정 예약)
        Magic    = 1 << 4,  // 마법 (미래 함정 예약)
    }
}
